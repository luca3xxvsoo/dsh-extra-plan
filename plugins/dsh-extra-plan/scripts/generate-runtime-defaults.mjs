#!/usr/bin/env node
// Generate the runtime fallback and the preset declaration patch.
// Both outputs are replaced only after source parsing and validation succeed.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parsePresetYaml, resolveTemplateSettingDefault } from '../lib/preset-settings.js'

const HERE = dirname(fileURLToPath(import.meta.url))
export const DEFAULT_SOURCE = resolve(HERE, '..', 'assets', 'presets', 'extra-plan', 'agent.cordis.yml')
export const DEFAULT_OUTPUT = resolve(HERE, '..', 'lib', 'preset-defaults.generated.js')
export const DEFAULT_META_SOURCE = resolve(HERE, '..', 'assets', 'presets', 'extra-plan', 'preset.yml')
export const DEFAULT_PATCH_OUTPUT = resolve(HERE, '..', 'assets', 'presets', 'extra-plan', 'preset-patch.generated.yml')

// 预设新载体（dsh 0.1.7-rc.1）：预设不再是宿主读取 .agent-presets 的目录分发，
// 而是 profile patch 根级 insert 一行声明行（name = @deepseek-ai/dsh-agent-preset），
// 顶层 agent 组合逐字进入该行 config.plugins。产物 = preset-patch.generated.yml，
// 由 package.json dsh.bundle.patch 数组随 cordis.patch.yml 一并装载。
export const PRESET_ID = 'extra-plan'
export const PRESET_ORDER = 100
// 声明行 config.plugins 内条目缩进：根级条目（0 缩进）平移 PLUGINS_INDENT 列。
export const PLUGINS_INDENT = 10

export function renderRuntimeDefaults(defaultText) {
  const budget = resolveTemplateSettingDefault(defaultText, 'exploreBudget')
  const suffix = resolveTemplateSettingDefault(defaultText, 'plannerPromptSuffix')
  return [
    '// GENERATED FILE - DO NOT EDIT.',
    '// Generated by plugins/dsh-extra-plan/scripts/generate-runtime-defaults.mjs.',
    'export const DEFAULT_EXPLORE_BUDGET = ' + String(budget),
    'export const DEFAULT_PLANNER_PROMPT_SUFFIX = ' + JSON.stringify(suffix),
    '',
  ].join('\n')
}

/**
 * 抽取 agent.cordis.yml 的顶层条目区间（首个「- id:」行到文件末尾），整段平移
 * PLUGINS_INDENT 列后作为声明行 config.plugins 的值——注释、锚点、!!js 表达式逐字保留，
 * group 行（cordis:group + group: true + config 子行数组）与 isolate 键原样随行。
 */
export function topLevelRowsOf(defaultText) {
  const lines = String(defaultText).split('\n')
  const start = lines.findIndex((line) => /^- (?:id|insert):/.test(line))
  if (start === -1) throw new Error('agent.cordis.yml 顶层条目缺失（未找到根级「- id:」行）')
  let end = lines.length
  while (end > start && lines[end - 1].trim() === '') end -= 1
  const block = lines.slice(start, end)
  if (block.length === 0) throw new Error('agent.cordis.yml 顶层条目为空')
  return block
}

function indentBlock(block) {
  const pad = ' '.repeat(PLUGINS_INDENT)
  return block.map((line) => (line === '' ? line : pad + line))
}

function quoteYamlSingle(value) {
  return "'" + String(value).replace(/'/g, "''") + "'"
}

export function renderPresetPatch(defaultText, metaText) {
  const rows = topLevelRowsOf(defaultText)
  const meta = parsePresetYaml(metaText)
  if (meta === null || typeof meta !== 'object') throw new Error('preset.yml 解析结果不是对象')
  if (typeof meta.name !== 'string' || meta.name === '') throw new Error('preset.yml 缺少 name')
  if (typeof meta.description !== 'string' || meta.description === '') throw new Error('preset.yml 缺少 description')
  const head = [
    '# GENERATED FILE - DO NOT EDIT.',
    '# Generated by plugins/dsh-extra-plan/scripts/generate-runtime-defaults.mjs.',
    '# 预设声明行（dsh 0.1.7-rc.1 载体）：config.plugins = agent.cordis.yml 顶层条目逐字平移。',
    '- insert:',
    '    - id: preset-' + PRESET_ID,
    "      name: '@deepseek-ai/dsh-agent-preset'",
    '      config:',
    '        id: ' + PRESET_ID,
    '        name: ' + quoteYamlSingle(meta.name),
    '        description: ' + quoteYamlSingle(meta.description),
    '        order: ' + String(PRESET_ORDER),
    '        plugins:',
  ]
  return head.concat(indentBlock(rows)).join('\n') + '\n'
}

function assertParses(text, what) {
  try {
    parsePresetYaml(text)
  } catch (error) {
    throw new Error(what + ' YAML parse failed: ' + (error instanceof Error ? error.message : String(error)))
  }
}

function writeOrCheck(output, rendered, check, label) {
  if (check) {
    if (!existsSync(output)) throw new Error(label + ' missing: ' + output)
    const existing = readFileSync(output, 'utf8')
    if (existing !== rendered) throw new Error(label + ' out of date: ' + output)
    return
  }
  mkdirSync(dirname(output), { recursive: true })
  writeFileSync(output, rendered, 'utf8')
}

/**
 * @param options.sourcePath / outputPath 自定义（夹具）路径时，默认不再触碰仓库内的
 *   预设声明产物——只有走全仓默认路径（或显式给 patchOutputPath）才生成 preset-patch。
 * @param options.patchOutputPath 显式路径；显式传 null 关闭声明行产物生成。
 */
export function generateRuntimeDefaults(options = {}) {
  const sourcePath = options.sourcePath === undefined ? DEFAULT_SOURCE : options.sourcePath
  const outputPath = options.outputPath === undefined ? DEFAULT_OUTPUT : options.outputPath
  const metaSourcePath = options.metaSourcePath === undefined ? DEFAULT_META_SOURCE : options.metaSourcePath
  const check = options.check === true
  const source = resolve(sourcePath)
  const output = resolve(outputPath)
  const metaSource = resolve(metaSourcePath)
  const usesRepositoryDefaults = source === DEFAULT_SOURCE && output === DEFAULT_OUTPUT
  const patchOutput = options.patchOutputPath === undefined
    ? (usesRepositoryDefaults ? DEFAULT_PATCH_OUTPUT : null)
    : (options.patchOutputPath === null ? null : resolve(options.patchOutputPath))
  // Read, parse, validate, and render before touching output: a bad template keeps last-known-good bytes.
  const sourceText = readFileSync(source, 'utf8')
  const rendered = renderRuntimeDefaults(sourceText)
  let renderedPatch = null
  let metaText = null
  if (patchOutput !== null) {
    metaText = readFileSync(metaSource, 'utf8')
    assertParses(metaText, 'preset.yml')
    renderedPatch = renderPresetPatch(sourceText, metaText)
    // 产物自校验：声明行产物必须能先被 !!js-preserving schema 解析，再允许落盘。
    assertParses(renderedPatch, 'preset-patch.generated.yml')
  }
  if (check) {
    writeOrCheck(output, rendered, true, 'generated output')
    if (patchOutput !== null) writeOrCheck(patchOutput, renderedPatch, true, 'generated preset patch')
    return { source, output, metaSource, patchOutput, rendered, renderedPatch, changed: false }
  }
  writeOrCheck(output, rendered, false, 'generated output')
  if (patchOutput !== null) writeOrCheck(patchOutput, renderedPatch, false, 'generated preset patch')
  return { source, output, metaSource, patchOutput, rendered, renderedPatch, changed: true }
}

function invokedAsMain() {
  if (!process.argv[1]) return false
  return resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
}

if (invokedAsMain()) {
  try {
    const check = process.argv.includes('--check')
    const result = generateRuntimeDefaults({ check })
    process.stdout.write((check ? '[check] ' : '[generated] ') + result.output + '\n')
    if (result.patchOutput !== null) process.stdout.write((check ? '[check] ' : '[generated] ') + result.patchOutput + '\n')
  } catch (error) {
    process.stderr.write('[generate-runtime-defaults] ' + (error instanceof Error ? error.message : String(error)) + '\n')
    process.exitCode = 1
  }
}
