#!/usr/bin/env node
// Generate the runtime fallback from the agent.cordis.yml template.
// GENERATED output is replaced only after source parsing and validation succeed.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { resolveTemplateSettingDefault } from '../lib/preset-settings.js'

const HERE = dirname(fileURLToPath(import.meta.url))
export const DEFAULT_SOURCE = resolve(HERE, '..', 'assets', 'presets', 'extra-plan', 'agent.cordis.yml')
export const DEFAULT_OUTPUT = resolve(HERE, '..', 'lib', 'preset-defaults.generated.js')

export function renderRuntimeDefaults(defaultText) {
  const value = resolveTemplateSettingDefault(defaultText, 'exploreBudget')
  return [
    '// GENERATED FILE - DO NOT EDIT.',
    '// Generated by plugins/dsh-extra-plan/scripts/generate-runtime-defaults.mjs.',
    'export const DEFAULT_EXPLORE_BUDGET = ' + String(value),
    '',
  ].join('\n')
}

export function generateRuntimeDefaults({ sourcePath = DEFAULT_SOURCE, outputPath = DEFAULT_OUTPUT, check = false } = {}) {
  const source = resolve(sourcePath)
  const output = resolve(outputPath)
  // Read, parse, validate, and render before touching output: a bad template keeps last-known-good bytes.
  const sourceText = readFileSync(source, 'utf8')
  const rendered = renderRuntimeDefaults(sourceText)
  if (check) {
    if (!existsSync(output)) throw new Error('generated output missing: ' + output)
    const existing = readFileSync(output, 'utf8')
    if (existing !== rendered) throw new Error('generated output out of date: ' + output)
    return { source, output, rendered, changed: false }
  }
  mkdirSync(dirname(output), { recursive: true })
  writeFileSync(output, rendered, 'utf8')
  return { source, output, rendered, changed: true }
}

function invokedAsMain() {
  if (!process.argv[1]) return false
  return resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
}

if (invokedAsMain()) {
  try {
    const check = process.argv.includes('--check')
    const result = generateRuntimeDefaults({ check })
    process.stdout.write((check ? '[check] ' : '[generated] ') + result.output + '\n')
  } catch (error) {
    process.stderr.write('[generate-runtime-defaults] ' + (error instanceof Error ? error.message : String(error)) + '\n')
    process.exitCode = 1
  }
}
