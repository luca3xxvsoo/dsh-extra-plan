export const CLIENT_FIELDS_BEGIN = '// BEGIN GENERATED SETTINGS FIELDS'
export const CLIENT_FIELDS_END = '// END GENERATED SETTINGS FIELDS'
const CLIENT_FIELD_METADATA_KEYS = Object.freeze(['options', 'optionLocale', 'locale', 'section', 'min', 'step', 'hint'])

function clientFieldMetadata(definition) {
  if (definition === null || typeof definition !== 'object' || definition.ui === null || typeof definition.ui !== 'object') {
    throw new Error('客户端字段缺少 ui 元数据：' + String(definition && definition.key))
  }
  const metadata = { key: definition.key, control: definition.ui.control }
  for (const key of CLIENT_FIELD_METADATA_KEYS) {
    const value = definition.ui[key]
    if (value === undefined) continue
    if (key === 'options') metadata.options = [...value]
    else if (key === 'optionLocale') metadata.optionLocale = { ...value }
    else metadata[key] = value
  }
  return metadata
}

function clientFieldLines(name, definitions) {
  return [
    '    const ' + name + ' = Object.freeze([',
    ...definitions.map((definition) => '      ' + JSON.stringify(clientFieldMetadata(definition)) + ','),
    '    ]);',
  ]
}

export function renderClientFieldBlock(definitions = SETTING_DEFINITIONS) {
  const list = Array.isArray(definitions) ? definitions : SETTING_DEFINITIONS
  const extra = list.filter((definition) => definition.group === 'extra-plan')
  const host = list.filter((definition) => definition.group === 'host-rows')
  if (extra.length !== 8 || host.length !== 2) throw new Error('客户端字段分组必须为 8 项 extra-plan + 2 项 host-rows')
  return [
    ...clientFieldLines('EXTRA_FIELDS', extra),
    '',
    ...clientFieldLines('HOST_ROW_FIELDS', host),
    '    const ALL_FIELDS = Object.freeze(EXTRA_FIELDS.concat(HOST_ROW_FIELDS));',
  ].join('\n')
}

function markerMatches(text, marker) {
  const escaped = marker.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  return [...String(text).matchAll(new RegExp('^[ \t]*' + escaped + '[ \t]*\\r?$', 'gm'))]
}

function clientFieldMarkerRange(clientText) {
  const begin = markerMatches(clientText, CLIENT_FIELDS_BEGIN)
  const end = markerMatches(clientText, CLIENT_FIELDS_END)
  if (begin.length !== 1 || end.length !== 1) throw new Error('客户端字段生成标记必须各恰有一处')
  const beginEnd = clientText.indexOf('\n', begin[0].index)
  const contentStart = beginEnd === -1 ? clientText.length : beginEnd + 1
  if (end[0].index < contentStart) throw new Error('客户端字段生成标记顺序逆序')
  return { contentStart, contentEnd: end[0].index, eol: clientText.includes('\r\n') ? '\r\n' : '\n' }
}

export function renderClientFields(clientText, definitions = SETTING_DEFINITIONS) {
  if (typeof clientText !== 'string') throw new Error('客户端源必须为字符串')
  const range = clientFieldMarkerRange(clientText)
  const block = renderClientFieldBlock(definitions).replaceAll('\n', range.eol)
  return clientText.slice(0, range.contentStart) + block + range.eol + clientText.slice(range.contentEnd)
}

/** 顶格 YAML 文档分隔行（作者源第一文档结束、第二文档开始的唯一边界）。 */
const DOCUMENT_SEPARATOR = /^---\s*$/

function separatorIndexOf(lines) {
  return lines.findIndex((line) => DOCUMENT_SEPARATOR.test(line))
}

/** 抽取 agent.cordis.yml 第一文档的顶层条目区间（结束边界=首个「---」行），保留注释、group、isolate 与 !!js。 */
export function topLevelRowsOf(defaultText) {
  const lines = String(defaultText).split('\n')
  const start = lines.findIndex((line) => /^- (?:id|insert):/.test(line))
  if (start === -1) throw new Error('agent.cordis.yml 顶层条目缺失（未找到根级「- id:」行）')
  const separator = separatorIndexOf(lines)
  let end = separator === -1 ? lines.length : separator
  while (end > start && lines[end - 1].trim() === '') end -= 1
  const block = lines.slice(start, end)
  if (block.length === 0) throw new Error('agent.cordis.yml 顶层条目为空')
  return block
}

/** 抽取 agent.cordis.yml 第二文档原文（分隔行之后全部行，保留注释与工具面原文）；缺分隔行即抛。 */
export function secondDocumentOf(defaultText) {
  const lines = String(defaultText).split('\n')
  const separator = separatorIndexOf(lines)
  if (separator === -1) throw new Error('agent.cordis.yml 缺少第二文档分隔行「---」')
  return lines.slice(separator + 1).join('\n')
}

function indentBlock(block, columns = PLUGINS_INDENT) {
  const pad = ' '.repeat(columns)
  return block.map((line) => (line === '' ? line : pad + line))
}

function indentOf(line) {
  let count = 0
  while (count < line.length && line[count] === ' ') count += 1
  return count
}

function shiftBlock(block, delta) {
  if (delta === 0) return block.slice()
  return block.map((line) => {
    if (line.trim() === '') return ''
    const next = indentOf(line) + delta
    if (next < 0) throw new Error('缩进平移越界：' + JSON.stringify(line))
    return ' '.repeat(next) + line.slice(indentOf(line))
  })
}

/**
 * 取出「起始行 + 其后更深缩进的非空行」为一整块 raw 文本：
 * 遇到缩进 <= base 的非空行即结束（同级注释留给外层），尾部空行剔除。
 */
export function rawBlockFrom(lines, startIndex, baseIndent) {
  if (startIndex < 0 || startIndex >= lines.length) throw new Error('raw 块起点越界')
  const block = [lines[startIndex]]
  for (let index = startIndex + 1; index < lines.length; index += 1) {
    const line = lines[index]
    if (line.trim() === '') { block.push(''); continue }
    if (indentOf(line) <= baseIndent) break
    block.push(line)
  }
  while (block.length > 1 && block[block.length - 1].trim() === '') block.pop()
  return block
}

function quoteYamlSingle(value) {
  return "'" + String(value).replace(/'/g, "''") + "'"
}

function assertDefinition(definition, label) {
  if (definition === null || typeof definition !== 'object' || Array.isArray(definition)) throw new Error(label + ' definition 不是对象')
  if (definition.id !== PRESET_ID) throw new Error(label + ' id 必须为 ' + PRESET_ID)
  if (typeof definition.name !== 'string' || definition.name === '') throw new Error(label + ' 缺少 name')
  if (typeof definition.description !== 'string' || definition.description === '') throw new Error(label + ' 缺少 description')
  if (!Number.isInteger(definition.order)) throw new Error(label + ' order 必须为整数')
  if (!Array.isArray(definition.plugins) || definition.plugins.length !== 17) throw new Error(label + ' plugins 顶层必须恰有 17 条')
  if (definition.plugins.some((row) => row === null || typeof row !== 'object' || row.insert !== undefined)) throw new Error(label + ' plugins 不得含 Loader insert wrapper')
}

export function renderPresetDefinition(defaultText, metaText) {
  const rows = topLevelRowsOf(defaultText)
  const meta = parsePresetYaml(metaText)
  if (meta === null || typeof meta !== 'object' || Array.isArray(meta)) throw new Error('preset.yml 解析结果不是对象')
  if (typeof meta.name !== 'string' || meta.name === '') throw new Error('preset.yml 缺少 name')
  if (typeof meta.description !== 'string' || meta.description === '') throw new Error('preset.yml 缺少 description')
  const rendered = [
    '# GENERATED FILE - DO NOT EDIT.',
    '# Generated by plugins/dsh-extra-plan/scripts/generate-runtime-defaults.mjs.',
    '# 纯 preset definition；由 preset-sync 内部交给官方 @deepseek-ai/dsh-agent-preset adapter。',
    '# plugins = agent.cordis.yml 顶层条目逐字平移，保留 group/isolate/!!js 原文。',
    'id: ' + PRESET_ID,
    'name: ' + quoteYamlSingle(meta.name),
    'description: ' + quoteYamlSingle(meta.description),
    'order: ' + String(PRESET_ORDER),
    'plugins:',
  ].concat(indentBlock(rows)).join('\n') + '\n'
  assertDefinition(parsePresetYaml(rendered), '生成 definition')
  return rendered
}

/** extra-plan 行（主 definition 内 group 子行）的 raw 块：id 行 + name 行 + 整段 config。 */
function mainExtraPlanRowBlock(definitionText) {
  const lines = String(definitionText).split('\n')
  const start = lines.findIndex((line) => /^\s*- id: extra-plan$/.test(line))
  if (start === -1) throw new Error('主 definition 缺少 extra-plan 行')
  const base = indentOf(lines[start])
  const block = rawBlockFrom(lines, start, base)
  const nameLine = block.find((line) => /^\s*name:/.test(line))
  if (nameLine === undefined) throw new Error('主 definition 的 extra-plan 行缺少 name')
  const configIndex = block.findIndex((line) => /^\s*config:$/.test(line))
  if (configIndex === -1) throw new Error('主 definition 的 extra-plan 行缺少 config')
  return { block, configBlock: block.slice(configIndex) }
}

/** 角色源里某角色的 personaPrefix 折叠块 raw 行（首行为 key 行）。 */
function personaPrefixBlock(roleText, personaText) {
  const lines = String(roleText).split('\n')
  const start = lines.findIndex((line) => line.trim() === 'personaPrefix: >-')
  if (start === -1) throw new Error('角色源缺少 personaPrefix: >- 块')
  const keyIndent = indentOf(lines[start])
  // 定位属于本条目的 personaPrefix：按角色顺序逐个消费，这里以 personaText 内容做唯一性校验。
  const candidates = []
  for (let index = 0; index < lines.length; index += 1) {
    if (lines[index].trim() === 'personaPrefix: >-') candidates.push(index)
  }
  for (const index of candidates) {
    const block = rawBlockFrom(lines, index, indentOf(lines[index]))
    const body = block.slice(1)
    const text = [
      'x:',
      '  personaPrefix: >-',
      ...body,
      '',
    ].join('\n')
    let parsed
    try { parsed = parsePresetYaml(text) } catch { continue }
    if (parsed !== null && typeof parsed === 'object' && parsed.x !== undefined && parsed.x.personaPrefix === personaText) {
      return { body }
    }
  }
  throw new Error('角色源 personaPrefix 块与解析值不匹配（' + keyIndent + '）')
}

/** 角色源里 tools 列表的 raw 行（首行为「tools:」行）。 */
function roleToolsBlock(roleText, roleIndex, roleCount) {
  const lines = String(roleText).split('\n')
  const starts = []
  for (let index = 0; index < lines.length; index += 1) {
    if (lines[index].trim() === 'tools:') starts.push(index)
  }
  if (starts.length !== roleCount) throw new Error('角色源 tools: 行数与角色数不符（' + starts.length + '/' + roleCount + '）')
  const index = starts[roleIndex]
  const base = indentOf(lines[index])
  const block = rawBlockFrom(lines, index, base)
  return { block: block.slice(1) }
}

/** 按行 id 深度优先查子行（含 group 行的 config 子行数组），与 preset-sync 的定位口径同形；找不到返回 null。 */
function findRowById(rows, rowId) {
  if (!Array.isArray(rows)) return null
  for (const row of rows) {
    if (row === null || typeof row !== 'object' || Array.isArray(row)) continue
    if (row.id === rowId) return row
    if (Array.isArray(row.config)) {
      const nested = findRowById(row.config, rowId)
      if (nested !== null) return nested
    }
  }
  return null
}

/**
 * 主 definition 里 tool-presentation 行的默认 mode（角色 definition 末行取同一个值）。
 * 行缺失/叶缺失/值非法/解析异常一律回落内置默认值，不抛错。
 */
export function mainToolPresentationMode(definitionText) {
  try {
    const setting = SETTING_DEFINITIONS.find((item) => item.key === 'toolPresentationMode')
    const parsed = parsePresetYaml(definitionText)
    const plugins = parsed !== null && typeof parsed === 'object' && Array.isArray(parsed.plugins) ? parsed.plugins : []
    const row = findRowById(plugins, ROLE_LAST_ROW_ID)
    const mode = row !== null && row.config !== null && typeof row.config === 'object' && !Array.isArray(row.config) ? row.config.mode : undefined
    if (!validateSettingValue(setting, mode)) return DEFAULT_TOOL_PRESENTATION_MODE
    return normalizeSettingValue(setting, mode)
  } catch {
    return DEFAULT_TOOL_PRESENTATION_MODE
  }
}

function assertRoleSource(roles, label = '角色源') {
  if (!Array.isArray(roles) || roles.length !== ROLE_IDS.length) throw new Error(label + ' 必须恰有 ' + ROLE_IDS.length + ' 个角色')
  const ids = roles.map((role) => role !== null && typeof role === 'object' ? role.id : undefined)
  if (JSON.stringify(ids) !== JSON.stringify(ROLE_IDS)) throw new Error(label + ' id 顺序/取值必须为 ' + ROLE_IDS.join(','))
  const orders = roles.map((role) => role.order)
  if (JSON.stringify(orders) !== JSON.stringify(ROLE_ORDERS)) throw new Error(label + ' order 必须为 ' + ROLE_ORDERS.join(','))
  for (const role of roles) {
    if (typeof role.name !== 'string' || role.name === '') throw new Error(label + ' ' + role.id + ' 缺少中文 name')
    if (typeof role.description !== 'string' || role.description === '') throw new Error(label + ' ' + role.id + ' 缺少 description')
    if (typeof role.personaPrefix !== 'string' || role.personaPrefix === '') throw new Error(label + ' ' + role.id + ' 缺少 personaPrefix')
    if (!Array.isArray(role.tools) || role.tools.length === 0) throw new Error(label + ' ' + role.id + ' 缺少 tools 行')
    if (role.gateWords !== undefined) throw new Error(label + ' ' + role.id + ' 不得手写 gateWords（唯一编辑位置是 agent.cordis.yml）')
    for (const row of role.tools) {
      if (row === null || typeof row !== 'object' || typeof row.name !== 'string' || row.name === '') throw new Error(label + ' ' + role.id + ' 的 tools 行缺少 name')
      if (row.insert !== undefined) throw new Error(label + ' ' + role.id + ' 的 tools 行不得含 insert wrapper')
      // 生成器在 plugins 末尾固定追加恰一行 tool-presentation：作者源手写会产生第二行（宿主判为矛盾、拒绝挂载）。
      if (row.id === ROLE_LAST_ROW_ID || row.name === ROLE_LAST_ROW_NAME) throw new Error(label + ' ' + role.id + ' 不得手写 tool-presentation 行（由生成器固定追加恰一行）')
    }
  }
  return roles
}

function assertRoleDefinition(definition, role, label, presentationMode) {
  if (definition === null || typeof definition !== 'object' || Array.isArray(definition)) throw new Error(label + ' 不是对象')
  if (definition.id !== role.id) throw new Error(label + ' id 必须为 ' + role.id)
  if (definition.name !== role.name) throw new Error(label + ' name 与作者源不符')
  if (definition.description !== role.description) throw new Error(label + ' description 与作者源不符')
  if (definition.order !== role.order) throw new Error(label + ' order 与作者源不符')
  if (!Array.isArray(definition.plugins) || definition.plugins.length !== role.tools.length + ROLE_FIRST_ROW_IDS.length + 1) throw new Error(label + ' plugins 行数不符（应为首两行 + tools 行 + 末行 tool-presentation）')
  if (definition.plugins[0].id !== ROLE_FIRST_ROW_IDS[0] || definition.plugins[0].name !== '@deepseek-ai/dsh-persona') throw new Error(label + ' 首行必须是 dsh-persona')
  if (definition.plugins[0].config === undefined || definition.plugins[0].config.prefix !== role.personaPrefix) throw new Error(label + ' persona prefix 必须逐字等于 personaPrefix')
  if (definition.plugins[1].id !== ROLE_FIRST_ROW_IDS[1] || definition.plugins[1].name !== 'dsh-extra-plan') throw new Error(label + ' 第二行必须是 dsh-extra-plan')
  if (definition.plugins.some((row) => row === null || typeof row !== 'object' || row.insert !== undefined)) throw new Error(label + ' 不得含 Loader insert wrapper')
  // 同一 definition 内绝不允许第二行 tool-presentation（宿主判为矛盾并拒绝挂载）。
  const presentationRows = definition.plugins.filter((row) => row.id === ROLE_LAST_ROW_ID)
  if (presentationRows.length !== 1) throw new Error(label + ' 必须恰有一行 tool-presentation（实际 ' + presentationRows.length + ' 行）')
  const lastRow = definition.plugins[definition.plugins.length - 1]
  if (lastRow.id !== ROLE_LAST_ROW_ID || lastRow.name !== ROLE_LAST_ROW_NAME) throw new Error(label + ' 末行必须是 tool-presentation / ' + ROLE_LAST_ROW_NAME)
  if (lastRow.config === null || typeof lastRow.config !== 'object' || Array.isArray(lastRow.config)) throw new Error(label + ' tool-presentation 行必须带 config 对象')
  if (lastRow.config.mode !== presentationMode) throw new Error(label + ' tool-presentation.config.mode 必须与主 definition 同 id 行一致')
  return definition
}

/**
 * 渲染 4 个角色 definition：plugins = [dsh-persona(prefix=personaPrefix),
 * dsh-extra-plan(主预设同 id 行 config 逐字复制), ...角色 tools 行,
 * tool-presentation(恰一行，config.mode 取主 definition 同 id 行的默认值)]。
 */
export function renderRoleDefinitions(roleText, definitionText) {
  const roles = assertRoleSource(parsePresetYaml(roleText))
  const mainExtra = mainExtraPlanRowBlock(definitionText)
  const mainParsed = parsePresetYaml(mainExtra.block.join('\n'))
  const mainRow = Array.isArray(mainParsed) ? mainParsed[0] : mainParsed
  const mainConfigJson = JSON.stringify(mainRow !== null && typeof mainRow === 'object' && mainRow.config !== undefined ? mainRow.config : undefined)
  if (mainConfigJson === undefined) throw new Error('主 definition 的 extra-plan 行缺少 config')
  const configBlock = shiftBlock(mainExtra.configBlock, -4)
  const presentationMode = mainToolPresentationMode(definitionText)
  const presentationBlock = [
    '  - id: ' + ROLE_LAST_ROW_ID,
    "    name: '" + ROLE_LAST_ROW_NAME + "'",
    '    config:',
    '      mode: ' + presentationMode,
  ]
  return roles.map((role, index) => {
    const persona = personaPrefixBlock(roleText, role.personaPrefix)
    const tools = roleToolsBlock(roleText, index, roles.length)
    const rendered = [
      '# GENERATED FILE - DO NOT EDIT.',
      '# Generated by plugins/dsh-extra-plan/scripts/generate-runtime-defaults.mjs（源：agent.cordis.yml 第二文档）。',
      '# 角色预设 definition：dsh-persona 取 personaPrefix 原文，dsh-extra-plan 的行 config 由主预设同 id 行逐字复制，',
      '# 其余为角色 tools 行，plugins 末尾固定追加恰一行 tool-presentation（config.mode 取主预设同 id 行的默认值）。',
      '# 人设与工具面在这里承载；主预设不再写 persona/toolFilter/backgroundMode。',
      'id: ' + role.id,
      'name: ' + quoteYamlSingle(role.name),
      'description: ' + quoteYamlSingle(role.description),
      'order: ' + String(role.order),
      'plugins:',
      '  - id: persona',
      "    name: '@deepseek-ai/dsh-persona'",
      '    config:',
      '      prefix: >-',
      ...persona.body,
      '  - id: extra-plan',
      "    name: 'dsh-extra-plan'",
      ...configBlock,
      ...shiftBlock(tools.block, -2),
      ...presentationBlock,
    ].join('\n') + '\n'
    const parsed = parsePresetYaml(rendered)
    assertRoleDefinition(parsed, role, '生成角色 definition ' + role.id, presentationMode)
    const copied = JSON.stringify(parsed.plugins[1].config)
    if (copied !== mainConfigJson) throw new Error('生成角色 definition ' + role.id + ' 的 extra-plan config 与主预设不逐字相等')
    return { roleId: role.id, order: role.order, text: rendered }
  })
}

function assertParses(text, what) {
  try {
    const parsed = parsePresetYaml(text)
    if (what === 'preset-definition.generated.yml') assertDefinition(parsed, what)
    return parsed
  } catch (error) {
    throw new Error(what + ' YAML parse failed: ' + (error instanceof Error ? error.message : String(error)))
  }
}

function checkOutput(output, rendered, label) {
  if (!existsSync(output)) throw new Error(label + ' missing: ' + output)
  const existing = readFileSync(output, 'utf8')
  if (existing !== rendered) throw new Error(label + ' out of date: ' + output)
}

const DEFAULT_PUBLISH_FS_OPS = Object.freeze({ copyFileSync, existsSync, mkdirSync, renameSync, unlinkSync, writeFileSync })
let publishSequence = 0

function publishFsOpsOf(overrides) {
  if (overrides === null || overrides === undefined || typeof overrides !== 'object') return DEFAULT_PUBLISH_FS_OPS
  return { ...DEFAULT_PUBLISH_FS_OPS, ...overrides }
}

function errorText(error) {
  return error instanceof Error ? error.message : String(error)
}

function uniquePaths(paths) {
  return [...new Set(paths)]
}

function cleanupPublishFiles(paths, ops) {
  const failures = []
  for (const path of uniquePaths(paths)) {
    try {
      if (ops.existsSync(path)) ops.unlinkSync(path)
    } catch (error) {
      failures.push(path + '（' + errorText(error) + '）')
    }
  }
  return failures
}

function restorePublishedEntry(entry, ops) {
  try {
    if (entry.originalExists) {
      if (ops.existsSync(entry.path)) ops.unlinkSync(entry.path)
      ops.copyFileSync(entry.pathBackup, entry.path, fsConstants.COPYFILE_EXCL)
      if (!ops.existsSync(entry.path)) throw new Error('恢复后目标未就位：' + entry.path)
    } else if (ops.existsSync(entry.path)) {
      ops.unlinkSync(entry.path)
    }
    return null
  } catch (error) {
    return entry.path + '（' + errorText(error) + '）'
  }
}

function publishFailure(stage, original, rollbackErrors, cleanupErrors, remainingPaths) {
  const details = []
  if (rollbackErrors.length > 0) details.push('恢复失败：' + rollbackErrors.join('；'))
  if (cleanupErrors.length > 0) details.push('清理失败：' + cleanupErrors.join('；'))
  if (remainingPaths.length > 0) details.push('残留/备份路径：' + remainingPaths.join('；'))
  const failure = new Error('生成链发布失败；阶段=' + stage + '；原始失败=' + errorText(original) + (details.length === 0 ? '' : '；' + details.join('；')))
  failure.cause = original
  failure.stage = stage
  failure.rollbackErrors = rollbackErrors
  failure.cleanupErrors = cleanupErrors
  failure.remainingPaths = remainingPaths
  return failure
}

function normalizedOutputEntries(entries) {
  const seen = new Map()
  return entries.map((entry) => {
    const path = resolve(entry.path)
    const previous = seen.get(path)
    if (previous !== undefined) throw new Error('生成目标重复：' + path + '（' + previous + ' 与 ' + entry.label + '）')
    seen.set(path, entry.label)
    return { ...entry, path }
  })
}

function publishGeneratedOutputs(entries, fsOps) {
  publishSequence += 1
  const suffix = String(process.pid) + '-' + String(Date.now()) + '-' + String(publishSequence)
  const prepared = entries.map((entry, index) => ({
    ...entry,
    tempPath: entry.path + '.tmp-' + suffix + '-' + String(index),
    pathBackup: entry.path + '.bak-' + suffix + '-' + String(index),
    originalExists: false,
  }))
  const tempPaths = prepared.map((entry) => entry.tempPath)
  const backupPaths = []
  const createdTempPaths = []
  const createdBackupPaths = []
  const publishAttempts = []
  const ops = publishFsOpsOf(fsOps)
  let stage = '准备'
  try {
    stage = '暂存'
    for (let index = 0; index < prepared.length; index += 1) {
      const entry = prepared[index]
      stage = '暂存第' + String(index + 1)
      ops.mkdirSync(dirname(entry.path), { recursive: true })
      entry.originalExists = ops.existsSync(entry.path)
      if (entry.originalExists) {
        backupPaths.push(entry.pathBackup)
        if (ops.existsSync(entry.pathBackup)) throw new Error('备份文件已存在：' + entry.pathBackup)
        createdBackupPaths.push(entry.pathBackup)
        ops.copyFileSync(entry.path, entry.pathBackup, fsConstants.COPYFILE_EXCL)
      }
      if (ops.existsSync(entry.tempPath)) throw new Error('临时文件已存在：' + entry.tempPath)
      createdTempPaths.push(entry.tempPath)
      ops.writeFileSync(entry.tempPath, entry.content, { encoding: 'utf8', flag: 'wx' })
    }
    stage = '发布'
    for (let index = 0; index < prepared.length; index += 1) {
      const entry = prepared[index]
      stage = '发布第' + String(index + 1)
      publishAttempts.push(entry)
      if (entry.originalExists) ops.unlinkSync(entry.path)
      ops.renameSync(entry.tempPath, entry.path)
      if (!ops.existsSync(entry.path)) throw new Error('发布后目标未就位：' + entry.path)
    }
  } catch (original) {
    const rollbackErrors = []
    for (let index = publishAttempts.length - 1; index >= 0; index -= 1) {
      const rollbackError = restorePublishedEntry(publishAttempts[index], ops)
      if (rollbackError !== null) rollbackErrors.push(rollbackError)
    }
    if (rollbackErrors.length > 0) {
      throw publishFailure(stage, original, rollbackErrors, [], uniquePaths([...tempPaths, ...backupPaths]))
    }
    const cleanupErrors = cleanupPublishFiles([...createdTempPaths, ...createdBackupPaths], ops)
    if (cleanupErrors.length > 0) {
      throw publishFailure(stage, original, [], cleanupErrors, uniquePaths([...tempPaths, ...backupPaths]))
    }
    throw publishFailure(stage, original, [], [], [])
  }
  const cleanupErrors = cleanupPublishFiles([...createdTempPaths, ...createdBackupPaths], ops)
  if (cleanupErrors.length > 0) {
    const cleanupError = new Error(cleanupErrors.join('；'))
    throw publishFailure('清理', cleanupError, [], cleanupErrors, uniquePaths([...tempPaths, ...backupPaths]))
  }
}


/**
 * @param options.sourcePath / outputPath 自定义夹具路径时，默认不触碰仓库 definition 资产。
 * @param options.definitionOutputPath 显式 definition 路径；传 null 关闭 definition 生成。
 * @param options.roleDefinitionDir 显式角色产出目录；传 null 关闭角色生成（角色作者源即 sourcePath 的第二文档）。
 */
export function generateRuntimeDefaults(options = {}) {
  const sourcePath = options.sourcePath === undefined ? DEFAULT_SOURCE : options.sourcePath
  const outputPath = options.outputPath === undefined ? DEFAULT_OUTPUT : options.outputPath
  const metaSourcePath = options.metaSourcePath === undefined ? DEFAULT_META_SOURCE : options.metaSourcePath
  const check = options.check === true
  const source = resolve(sourcePath)
  const output = resolve(outputPath)
  const metaSource = resolve(metaSourcePath)
  const usesRepositoryDefaults = source === DEFAULT_SOURCE && output === DEFAULT_OUTPUT
  const definitionOutput = options.definitionOutputPath === undefined
    ? (usesRepositoryDefaults ? DEFAULT_DEFINITION_OUTPUT : null)
    : (options.definitionOutputPath === null ? null : resolve(options.definitionOutputPath))
  const roleDir = options.roleDefinitionDir === undefined
    ? (definitionOutput === null ? null : (usesRepositoryDefaults ? PRESET_ASSET_DIR : null))
    : (options.roleDefinitionDir === null ? null : resolve(options.roleDefinitionDir))
  const clientOptionSelected = options.clientSourcePath !== undefined || options.clientOutputPath !== undefined
  const clientOutput = options.clientOutputPath === undefined
    ? (usesRepositoryDefaults && !clientOptionSelected ? DEFAULT_CLIENT_OUTPUT : null)
    : (options.clientOutputPath === null ? null : resolve(options.clientOutputPath))
  let clientSource = null
  if (clientOutput !== null) {
    clientSource = options.clientSourcePath === undefined
      ? (usesRepositoryDefaults && !clientOptionSelected ? DEFAULT_CLIENT_OUTPUT : null)
      : (options.clientSourcePath === null ? null : resolve(options.clientSourcePath))
    if (clientSource === null) throw new Error('客户端输出已启用但未提供 clientSourcePath')
  }
  // 角色作者源与主预设同文件：第二文档由同一份 sourceText 切分，不再读独立文件。
  const roleSource = roleDir === null ? null : source
  // 先读、解析、校验并渲染，再接触输出；坏模板/缺失输入保留 last-known-good 字节。
  const sourceText = readFileSync(source, 'utf8')
  const rendered = renderRuntimeDefaults(sourceText)
  let renderedDefinition = null
  let renderedRoles = []
  if (definitionOutput !== null) {
    const metaText = readFileSync(metaSource, 'utf8')
    assertParses(metaText, 'preset.yml')
    renderedDefinition = renderPresetDefinition(sourceText, metaText)
    assertParses(renderedDefinition, 'preset-definition.generated.yml')
  }
  if (roleDir !== null && renderedDefinition !== null) {
    const roleText = secondDocumentOf(sourceText)
    renderedRoles = renderRoleDefinitions(roleText, renderedDefinition)
  }
  let renderedClient = null
  if (clientOutput !== null) {
    const clientText = readFileSync(clientSource, 'utf8')
    renderedClient = renderClientFields(clientText, SETTING_DEFINITIONS)
    new Script(renderedClient, { filename: clientSource })
  }
  const roleOutputs = renderedRoles.map((role) => resolve(roleDefinitionFile(role.roleId, roleDir)))
  const outputEntries = normalizedOutputEntries([
    { path: output, content: rendered, label: 'generated output' },
    ...(definitionOutput === null ? [] : [{ path: definitionOutput, content: renderedDefinition, label: 'generated preset definition' }]),
    ...renderedRoles.map((role, index) => ({
      path: roleOutputs[index],
      content: role.text,
      label: 'generated role definition ' + role.roleId,
    })),
    ...(renderedClient === null ? [] : [{ path: clientOutput, content: renderedClient, label: 'generated client' }]),
  ])
  if (check) {
    for (const entry of outputEntries) checkOutput(entry.path, entry.content, entry.label)
    return { source, output, metaSource, definitionOutput, roleSource, roleOutputs, clientSource, clientOutput, rendered, renderedDefinition, renderedRoles, renderedClient, changed: false }
  }
  publishGeneratedOutputs(outputEntries, options.fsOps)
  return { source, output, metaSource, definitionOutput, roleSource, roleOutputs, clientSource, clientOutput, rendered, renderedDefinition, renderedRoles, renderedClient, changed: true }
}

function invokedAsMain() {
  if (!process.argv[1]) return false
  return resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
}

if (invokedAsMain()) {
  try {
    const check = process.argv.includes('--check')
    const result = generateRuntimeDefaults({ check })
    process.stdout.write((check ? '[check] ' : '[generated] ') + result.output + '\n')
    if (result.definitionOutput !== null) process.stdout.write((check ? '[check] ' : '[generated] ') + result.definitionOutput + '\n')
    for (const roleOutput of result.roleOutputs) process.stdout.write((check ? '[check] ' : '[generated] ') + roleOutput + '\n')
    if (result.clientOutput !== null) process.stdout.write((check ? '[check] ' : '[generated] ') + result.clientOutput + '\n')
  } catch (error) {
    process.stderr.write('[generate-runtime-defaults] ' + (error instanceof Error ? error.message : String(error)) + '\n')
    process.exitCode = 1
  }
}
